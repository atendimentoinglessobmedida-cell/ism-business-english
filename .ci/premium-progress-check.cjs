const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
process.chdir(path.join(__dirname,'..'));
const context={window:{}};vm.createContext(context);
for(const file of ['premium-courses.js','premium-special.js','premium-dialogues.js','premium-engine.js'])vm.runInContext(fs.readFileSync(file,'utf8'),context);
const E=context.window.ISMPremiumEngine,courses=context.window.ISM_PREMIUM_COURSES;
const clone=value=>JSON.parse(JSON.stringify(value));
const records=new Map(),writes=[];
const storage={read:k=>clone(records.get(k)||{}),write:(k,v)=>{records.set(k,clone(v));writes.push(k);return true;}};
const c=courses.find(c=>c.id==='P3'),original={done:{'P3.1':true},drafts:{'P3.1':'remote draft'},speaking:{'P3.1':true},lessons:{'P3.2':{done:true,draft:'authored draft'},'P3.99':{done:true,draft:'unknown preserved'}}};
records.set(E.legacyKey(c.id),clone(original));
const migrated=E.load(storage,c);
assert.equal(E.count(c,migrated),1,'unknown IDs do not increase progress');
assert.equal(migrated['P3.2'].draft,'authored draft');
assert.equal(migrated['P3.1'],undefined,'remote completion is not converted to authored completion');
assert.deepEqual(records.get(E.legacyKey(c.id)),original,'migration preserves source exactly');
assert.equal(writes.length,1);
assert.deepEqual(clone(E.load(storage,c)),clone(migrated));
assert.equal(writes.length,1,'migration is idempotent');
migrated['P3.3']={done:true,draft:'new work'};
E.save(storage,c,migrated);
assert.equal(E.count(c,E.load(storage,c)),2);
assert.deepEqual(records.get(E.legacyKey(c.id)),original,'saving authored work cannot erase remote records');
assert.equal(E.legacySummary(storage).done,1,'collections never share completion counts');
records.get(E.legacyKey(c.id)).done['P3.4']=true;
assert.equal(E.legacySummary(storage).done,2);
assert.equal(E.count(c,E.load(storage,c)),2,'remote updates cannot overwrite migrated authored work');
const empty=courses.find(c=>c.id==='P4');
records.set(E.legacyKey(empty.id),{done:{'P4.1':true},lessons:'invalid'});
assert.equal(Object.keys(E.load(storage,empty)).length,0,'malformed data is ignored safely');
records.set(E.key(empty.id),{collection:'authored-v1',lessons:{},custom:'preserve'});
records.set(E.legacyKey(empty.id),{lessons:{'P4.1':{done:true}}});
assert.equal(Object.keys(E.load(storage,empty)).length,0,'completed migration does not reimport stale source');
E.save(storage,empty,{});
assert.equal(records.get(E.key(empty.id)).custom,'preserve');
records.set(E.legacyKey('P1'),{lessons:{'13.1':true,'13.2':false,'13.3':{done:true}}});
assert.equal(E.legacySummary(storage).tracks[0].done,1,'objects are not legacy boolean completions');
records.set(E.legacyKey('P2'),{done:Object.fromEntries(Array.from({length:12},(_,i)=>[i,true]))});
assert.equal(E.legacySummary(storage).tracks[1].done,8,'legacy displays cannot exceed their declared total');
assert.equal(E.legacySummary(storage).total,88);
assert.equal(courses.reduce((n,c)=>n+c.lessons.length,0),57);
assert.equal(courses.length,7);
assert.equal(E.route('#P10/1',[{id:'P10',lessons:[[]]}]).index,0);
assert.equal(E.route('#P999/1',courses).course,null);
const study=fs.readFileSync('premium-study.js','utf8');
assert(study.includes('E.load(ISMStorage,c)'));
assert(study.includes('E.save(ISMStorage,c,state(c))'));
assert(study.includes('Progresso da coleção de prática aplicada'));
const index=fs.readFileSync('index.html','utf8');
assert(index.includes('ISMPremiumEngine.legacySummary(ISMStorage)'));
assert(index.indexOf('src="premium-engine.js')<index.indexOf('const premiumTracks='));
console.log('PASS: separate 88/8 remote and 57/7 authored catalogues; idempotent migration, source preservation, drafts, counts, routes, malformed records and renderer wiring.');
